async(page)=>{
  page.setDefaultTimeout(12000);
  const ok=(value,message)=>{if(!value)throw new Error(message);};
  const tenant='b128e444-cd57-4087-bcfe-c403051bbd8f',project='1498c59a-a789-4087-8069-4c99ebcbd63f',character='b6095818-3b79-47ea-ad5a-52ff517146fa';
  const origin='http://127.0.0.1:4311/?asset-validation=2';
  const read=()=>page.evaluate(async()=>{
    const t=location.hash.split('/')[3],id=new URLSearchParams(location.hash.split('?')[1]).get('asset');
    const asset=await(await fetch(`/v1/tenants/${t}/assets/${id}`)).json(),fixed=await(await fetch(`/v1/tenants/${t}/asset-revisions/${asset.currentRevisionId}`)).json();return {asset,fixed};
  });
  await page.goto(`${origin}#/app/t/${tenant}/assets`);
  await page.getByRole('button',{name:'新建资产',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'新建工作室共享资产',exact:true});
  await dialog.getByRole('combobox',{name:'资产类别',exact:true}).click();await page.getByRole('option',{name:'声音',exact:true}).click();
  await dialog.getByRole('textbox',{name:'资产名称',exact:true}).fill('林晚 · 共享声音设定');
  await dialog.getByRole('button',{name:'创建并准备固定版本',exact:true}).click();
  await page.getByRole('button',{name:'建立第一个固定版本',exact:true}).click();
  await page.getByRole('textbox',{name:'固定设定说明',exact:true}).fill('人工声音方向，未调用模型，也尚未录制正式配音。');
  await page.getByRole('textbox',{name:'声音说明',exact:true}).fill('v1：低声、克制，句尾保留气息。');
  await page.getByRole('button',{name:'保存为新的固定版本',exact:true}).click();
  await page.getByRole('textbox',{name:'固定设定说明',exact:true}).waitFor({state:'hidden'});
  const voice=await read();
  await page.goto(`${origin}#/app/t/${tenant}/p/${project}/assets?asset=${character}`);
  await page.getByRole('button',{name:'基于当前版本新建修订',exact:true}).click();
  await page.getByRole('button',{name:'选择声音固定版',exact:true}).click();
  const pick=page.getByRole('dialog',{name:'选择声音固定版',exact:true});
  await pick.getByRole('combobox',{name:'声音范围',exact:true}).click();await page.getByRole('option',{name:'工作室共享',exact:true}).click();
  await pick.getByRole('textbox',{name:'查找声音资产',exact:true}).fill('林晚 · 共享声音设定');
  await pick.getByRole('button',{name:'选择版本',exact:true}).click();
  await pick.getByRole('button',{name:'引入并使用 v1 固定版',exact:true}).click();
  await pick.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'保存为新的固定版本',exact:true}).click();
  await page.getByRole('textbox',{name:'固定设定说明',exact:true}).waitFor({state:'hidden'});
  const assigned=await read();ok(assigned.fixed.definition.defaultVoiceAssetRevisionId===voice.fixed.id,'Wrong fixed voice assigned');
  await page.goto(`${origin}#/app/t/${tenant}/assets?asset=${voice.asset.id}`);
  await page.getByRole('button',{name:'基于当前版本新建修订',exact:true}).click();
  await page.getByRole('textbox',{name:'声音说明',exact:true}).fill('v2：语速稍快，保留低声方向。');
  await page.getByRole('button',{name:'保存为新的固定版本',exact:true}).click();
  await page.getByRole('textbox',{name:'声音说明',exact:true}).waitFor({state:'hidden'});
  const updated=await read();ok(updated.fixed.number===2,'Shared voice revision not created');
  await page.goto(`${origin}#/app/t/${tenant}/p/${project}/assets?asset=${character}`);
  await page.getByText('默认声音固定版',{exact:true}).waitFor();
  await page.getByText('林晚 · 共享声音设定 · v1 · 草稿',{exact:true}).waitFor();
  const unchanged=await read();ok(unchanged.fixed.id===assigned.fixed.id&&unchanged.fixed.definition.defaultVoiceAssetRevisionId===voice.fixed.id,'Shared update auto-upgraded character');
  await page.getByText('默认声音固定版',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/asset-workspace/03-fixed-voice.png'});
  await page.goto(`${origin}#/app/t/${tenant}/assets?asset=${voice.asset.id}&revision=${voice.fixed.id}&targetProject=${project}`);
  await page.getByRole('button',{name:'将 v1 引入此项目',exact:true}).click();
  await page.getByText('已引入此固定版本，后续修订不会自动升级。',{exact:true}).waitFor();
  await page.getByText('有权查看的直接使用位置',{exact:true}).click();
  await page.getByText('林晚 · 固定版本复核 · v5',{exact:true}).waitFor();
  await page.getByRole('link',{name:'返回项目资产',exact:true}).click();
  await page.getByText('林晚 · 共享声音设定 · v1 · 草稿',{exact:true}).waitFor();
  const imports=await page.evaluate(async({tenant,project})=>await(await fetch(`/v1/tenants/${tenant}/projects/${project}/shared-imports`)).json(),{tenant,project});
  ok(imports.items.filter(i=>i.assetRevisionId===voice.fixed.id).length===1,'Same fixed import duplicated');
  ok(!imports.items.some(i=>i.assetRevisionId===updated.fixed.id),'New voice revision was implicitly imported');
  return {voiceAsset:voice.asset.id,importedFixedVoice:voice.fixed.id,newVoiceVersion:updated.fixed.id,characterVersion:assigned.fixed.id,characterStillUsesV1:true,repeatedImportCount:1,usageVisible:true};
}
