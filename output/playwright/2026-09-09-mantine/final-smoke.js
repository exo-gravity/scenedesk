async (page) => {
  const errors = [];
  const capture = error => errors.push(String(error));
  page.on('pageerror', capture);
  const checks = [];
  const check = (name, value, detail) => { checks.push({name, passed: Boolean(value), detail}); if (!value) throw new Error(name + ': ' + JSON.stringify(detail)); };
  await page.setViewportSize({width: 1512, height: 982});
  await page.goto('http://127.0.0.1:4313/#/scene/production');
  await page.reload({waitUntil: 'load'});
  await page.getByRole('textbox', {name: '本次提示词', exact: true}).waitFor();
  await page.waitForFunction(() => { const button = document.querySelector('button.btn[data-variant=filled]'); return button && getComputedStyle(button).backgroundColor === 'rgb(237, 184, 120)'; });
  const rendered = await page.getByRole('button', {name: '进入剪辑', exact: true}).evaluate(el => ({background: getComputedStyle(el).backgroundColor, height: el.getBoundingClientRect().height}));
  const inputPaint = await page.getByRole('textbox', {name: '本次提示词', exact: true}).evaluate(el => ({background: getComputedStyle(el).backgroundColor, border: getComputedStyle(el).borderTopColor}));
  check('production CSS keeps primary action colors and dimensions', rendered.background === 'rgb(237, 184, 120)' && rendered.height === 32, rendered);
  check('production CSS keeps neutral inputs and field contrast', inputPaint.background === 'rgb(36, 36, 36)' && inputPaint.border === 'rgb(115, 115, 115)', inputPaint);
  const handle = page.getByRole('separator');
  await handle.focus();
  await page.keyboard.press('ArrowLeft');
  await handle.dblclick();
  await page.waitForFunction(() => Math.abs(document.querySelector('[aria-label="镜头检查与生成面板"]').getBoundingClientRect().width - 380) < 1);
  check('double click restores the default fixed panel width', Math.abs((await page.getByRole('complementary', {name: '镜头检查与生成面板'}).boundingBox()).width - 380) < 1);
  await page.getByRole('heading', {name: '咖啡厅的旧钥匙', exact: true}).click();
  await page.mouse.move(220, 210);
  await page.screenshot({path: 'output/playwright/2026-09-09-mantine/final-production-1512.png'});
  await page.getByRole('button', {name: '准备生成', exact: true}).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('textbox', {name: '本次提示', exact: true}).waitFor();
  await page.screenshot({path: 'output/playwright/2026-09-09-mantine/final-generation-plan.png'});
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state: 'hidden'});
  await page.setViewportSize({width: 900, height: 900});
  check('collapsed navigation remains reachable at 900px', await page.getByRole('button', {name: '展开导航', exact: true}).isVisible());
  await page.getByRole('button', {name: '镜头面板', exact: true}).click();
  await page.waitForFunction(() => { const dialog = document.querySelector('[role=dialog]'); return dialog && dialog.getBoundingClientRect().right <= innerWidth + 1; });
  const cta = await page.getByRole('dialog').getByRole('button', {name: '准备生成', exact: true}).boundingBox();
  check('narrow drawer keeps generation action inside viewport', cta.y + cta.height <= 900, cta);
  await page.screenshot({path: 'output/playwright/2026-09-09-mantine/final-narrow-drawer.png'});
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state: 'hidden'});
  await page.setViewportSize({width: 1366, height: 900});
  await page.getByRole('textbox', {name: '本次提示词', exact: true}).waitFor();
  await page.screenshot({path: 'output/playwright/2026-09-09-mantine/final-production-1366.png'});
  await page.setViewportSize({width: 1512, height: 982});
  await page.goto('http://127.0.0.1:4313/#/design/');
  await page.getByRole('heading', {name: '同一套视觉，清楚的制作判断。'}).waitFor();
  check('lazy design route loads in production build', await page.getByRole('button', {name: '保存样板', exact: true}).isVisible());
  await page.screenshot({path: 'output/playwright/2026-09-09-mantine/final-design-controls.png'});
  await page.getByRole('tab', {name: '创作组件', exact: true}).click();
  await page.mouse.move(220, 210);
  await page.screenshot({path: 'output/playwright/2026-09-09-mantine/final-design-creative.png'});
  await page.getByRole('tab', {name: '状态与反馈', exact: true}).click();
  await page.screenshot({path: 'output/playwright/2026-09-09-mantine/final-design-states.png'});
  check('no runtime errors in production chunks', errors.length === 0, errors);
  page.off('pageerror', capture);
  return {passed: true, checks};
}
