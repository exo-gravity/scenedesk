async (page) => {
  page.setDefaultTimeout(15000);
  const tenant = 'b128e444-cd57-4087-bcfe-c403051bbd8f', project = '1498c59a-a789-4087-8069-4c99ebcbd63f';
  const voiceId = 'd8d31719-37a9-4162-bc2b-a51b005adee4', voiceV1 = 'd2dc183f-6566-4b3a-a19c-3302c355bc6f';
  const tenantPath = `/v1/tenants/${tenant}`, path = `${tenantPath}/projects/${project}`;
  const base = `http://127.0.0.1:4311/#/app/t/${tenant}/p/${project}`;
  const ok = (value, message) => { if (!value) throw new Error(message); };
  await page.goto(`${base}/content`); await page.reload();
  const request = (method, url, body, version) => page.evaluate(async ({ method, url, body, version }) => {
    const session = await (await fetch('/v1/session')).json();
    const response = await fetch(url, { method, headers: { 'content-type': 'application/json', 'x-csrf-token': session.csrfToken, 'idempotency-key': crypto.randomUUID(), ...(version !== undefined ? { 'if-match': `"${version}"` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    if (!response.ok) throw new Error(`${method} ${url}: ${response.status} ${JSON.stringify(await response.json())}`);
    return response.json();
  }, { method, url, body, version });
  const read = url => request('GET', url);
  const until = async (check, message) => {
    const start = Date.now();
    while (!await check()) { if (Date.now() - start > 15000) throw new Error(message); await page.waitForTimeout(100); }
  };
  const select = async (label, option) => { await page.getByRole('combobox', { name: label, exact: true }).click(); await page.getByRole('option', { name: option, exact: true }).click(); };
  const tree = await read(`${path}/content`), voice = await read(`${tenantPath}/assets/${voiceId}`);
  const scene = await request('POST', `${path}/scenes`, { episodeId: tree.episodes.find(e => e.status === 'active').id, title: `对白关联技术验收 ${Date.now()}`, position: 99, status: 'active', summary: '固定台词、导入声音及字幕草稿测试；不代表真实音频台词质量。', state: { characters: [], props: [], spatialNotes: '' } }, tree.revision);
  const dialogueId = await page.evaluate(() => crypto.randomUUID());
  const shotInput = { sceneId: scene.id, label: '对白核对', position: 0, status: 'active', spec: { intent: '核对钥匙去向', references: [], dialogue: [{ id: dialogueId, text: '钥匙还在原来的地方。', performance: '停顿后轻声回应', voiceAssetRevisionId: voiceV1 }] } };
  const shot = await request('POST', `${path}/shots`, shotInput, (await read(`${path}/content`)).revision);
  const errors = [], capture = e => errors.push(e.message); page.on('pageerror', capture);
  let workPath, cutId, route;
  try {
    await page.goto(`${base}/editing?scene=${scene.id}`); await page.setViewportSize({ width: 1366, height: 900 });
    await page.getByRole('button', { name: '新建剪辑', exact: true }).click();
    await page.getByRole('textbox', { name: '剪辑名称', exact: true }).fill(`对白声音字幕工作稿 ${Date.now()}`);
    await page.getByRole('button', { name: '建立空白剪辑', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    cutId = await page.evaluate(() => new URLSearchParams(location.hash.split('?')[1]).get('cut'));
    workPath = `${path}/cuts/${cutId}/work-draft`; route = `${base}/editing?scene=${scene.id}&cut=${cutId}`;
    const add = async (kind) => {
      if (!await page.getByRole('combobox', { name: '来源类型', exact: true }).isVisible()) await page.getByRole('button', { name: '加入片段', exact: true }).click();
      await select('来源类型', kind);
      await select('已验收素材', '四秒技术测试片 · 双人核对');
      await page.getByRole('button', { name: '明确加入工作稿', exact: true }).click();
      return page.evaluate(() => new URLSearchParams(location.hash.split('?')[1]).get('clip'));
    };
    const video = await add('视频素材'), audio = await add('视频的内嵌声音');
    if (!await page.getByRole('combobox', { name: '来源类型', exact: true }).isVisible()) await page.getByRole('button', { name: '加入片段', exact: true }).click();
    await page.getByRole('button', { name: '添加空白字幕条目', exact: true }).click();
    const subtitle = await page.evaluate(() => new URLSearchParams(location.hash.split('?')[1]).get('clip'));
    await until(async () => (await read(workPath)).document.timeline.tracks.length === 3, 'three clips not saved');
    const openNew = async clip => {
      await page.goto(`${route}&clip=${clip}`);
      if (!await page.getByText('对白、声音与字幕', { exact: true }).isVisible()) await page.getByRole('button', { name: '对白与声音', exact: true }).click();
      await page.getByRole('button', { name: '为当前片段建立关联', exact: true }).click();
      await select('台词所属镜头', '本场 · 对白核对 · 核对钥匙去向');
      await select('固定版台词', '1 · 钥匙还在原来的地方。');
    };
    await openNew(video);
    await page.getByRole('button', { name: '明确沿用台词要求的声音版', exact: true }).click();
    await page.getByRole('button', { name: '建立对白关联', exact: true }).click();
    await until(async () => (await read(workPath)).document.dramaBindings.length === 1, 'native binding did not save');
    await openNew(audio);
    await page.getByRole('checkbox', { name: '限定这句台词在源文件中的区间', exact: true }).check();
    await page.getByRole('textbox', { name: '台词源起点（秒）', exact: true }).fill('1.');
    await page.getByRole('textbox', { name: '关联备注', exact: true }).fill('保留尚未完成的对白区间');
    await page.goto(`${route}&clip=${subtitle}`);
    ok((await page.getByRole('combobox', { name: '关联目标片段', exact: true }).inputValue()).includes(audio.slice(0, 8)), 'selected clip silently retargeted unfinished form');
    await page.waitForTimeout(250); await page.reload();
    await page.getByRole('button', { name: '恢复并核对本机工作', exact: true }).click();
    if (!await page.getByText('对白、声音与字幕', { exact: true }).isVisible()) await page.getByRole('button', { name: '对白与声音', exact: true }).click();
    await page.getByRole('button', { name: `继续新建关联 ${audio.slice(0, 8)}`, exact: true }).click();
    ok(await page.getByRole('textbox', { name: '台词源起点（秒）', exact: true }).inputValue() === '1.', 'unfinished range lost after refresh');
    ok(await page.getByRole('textbox', { name: '关联备注', exact: true }).inputValue() === '保留尚未完成的对白区间', 'note lost after refresh');
    await page.getByRole('textbox', { name: '台词源起点（秒）', exact: true }).fill('0.250001');
    await page.getByRole('textbox', { name: '台词源终点（秒）', exact: true }).fill('2.000001');
    await page.getByRole('button', { name: '选择声音固定版', exact: true }).click();
    await select('声音范围', '工作室共享');
    await page.getByRole('dialog').getByText(voice.name, { exact: true }).locator('..').getByRole('button', { name: '选择版本', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: '引入并使用 v1', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: '先保存关联与待核对原声', exact: true }).click();
    await until(async () => (await read(workPath)).document.dramaBindings.length === 2, 'independent binding did not save');
    let work = await read(workPath);
    ok(work.issues.some(i => i.code === 'DUPLICATE_DIALOGUE_SOURCES'), 'two audible sources not diagnosed');
    ok(work.document.unresolvedEdits.some(i => i.kind === 'dialogue_binding'), 'pending original sound was discarded');
    ok(work.document.dramaBindings.find(b => b.clipId === audio).voiceAssetRevisionId === voiceV1, 'voice picker upgraded old version');
    await select(`原声处理 · ${video.slice(0, 8)}`, '静音该片段的整条混合音轨');
    await page.getByRole('button', { name: '应用关联修改', exact: true }).click();
    await until(async () => !(await read(workPath)).issues.some(i => i.code === 'DUPLICATE_DIALOGUE_SOURCES'), 'explicit mute did not clear duplicate source');
    work = await read(workPath);
    ok(work.document.timeline.tracks[0].items[0].muted && work.document.unresolvedEdits.length === 1, 'mute did not preserve independent pending task');
    await request('PUT', `${path}/shots/${shot.id}`, { ...shotInput, spec: { ...shotInput.spec, intent: '核对钥匙去向 · 新要求', dialogue: [{ ...shotInput.spec.dialogue[0], text: '新要求不会自动覆盖旧版。' }] } }, shot.revision);
    await page.reload();
    const restore = page.getByRole('button', { name: '恢复并核对本机工作', exact: true });
    if (!await page.getByText('对白、声音与字幕', { exact: true }).isVisible()) await page.getByRole('button', { name: '对白与声音', exact: true }).click();
    if (await restore.isVisible()) await restore.click();
    await page.getByText('当前镜头要求已有新版本；这里继续使用明确选择的固定旧版。', { exact: true }).waitFor();
    await page.getByText('要求 v1 · 钥匙还在原来的地方。', { exact: true }).waitFor();
    await page.goto(`${route}&clip=${subtitle}`);
    await page.getByRole('button', { name: '为当前片段建立关联', exact: true }).click();
    await select('台词所属镜头', '本场 · 对白核对 · 核对钥匙去向 · 新要求');
    await select('镜头要求固定版', 'v1 · 核对钥匙去向');
    await select('固定版台词', '1 · 钥匙还在原来的地方。');
    await page.getByRole('button', { name: '按固定台词整理字幕草稿', exact: true }).click();
    await until(async () => (await read(workPath)).document.dramaBindings.length === 3, 'subtitle binding did not save');
    work = await read(workPath);
    ok(work.document.timeline.tracks.find(t => t.kind === 'subtitle').items[0].text === '钥匙还在原来的地方。', 'fixed old text not copied');
    ok(work.document.unresolvedEdits.some(i => i.kind === 'subtitle_placement'), 'planned subtitle pretended to be verified');
    await page.getByRole('button', { name: '片段设置', exact: true }).click();
    await page.getByRole('textbox', { name: '字幕时长（秒）', exact: true }).fill('5');
    await until(async () => (await read(workPath)).issues.some(i => i.code === 'SUBTITLE_OUT_OF_BOUNDS'), 'unfinished subtitle bounds not diagnosed');
    await page.getByRole('button', { name: /^待处理 / }).click();
    await page.getByRole('button', { name: '处理完成，移除这项记录', exact: true }).first().click();
    await page.getByRole('button', { name: '确认完成此事项', exact: true }).click();
    await until(async () => (await read(workPath)).document.unresolvedEdits.length === 1, 'pending resolution not saved');
    ok((await read(workPath)).issues.some(i => i.code === 'SUBTITLE_OUT_OF_BOUNDS'), 'resolving a manual task cleared an automatic issue');
    await page.getByRole('button', { name: '片段设置', exact: true }).click();
    await page.getByRole('textbox', { name: '字幕时长（秒）', exact: true }).fill('1.000001');
    await until(async () => !(await read(workPath)).issues.some(i => i.code === 'SUBTITLE_OUT_OF_BOUNDS'), 'exact subtitle duration did not save');
    let usageCursor='',usageFound=false,usagePages=0;
    do {
      const usages = await read(`${tenantPath}/assets/${voiceId}/usages?limit=30${usageCursor?'&cursor='+encodeURIComponent(usageCursor):''}`);
      usagePages++;
      usageFound=usages.items.some(u => u.kind === 'cut_work_draft' && u.objectId === cutId && u.sceneId === scene.id);
      usageCursor=usages.nextCursor??'';
    } while(!usageFound&&usageCursor&&usagePages<100);
    ok(usageFound, 'current usage location absent from paginated results');
    await page.goto(`http://127.0.0.1:4311/#/app/t/${tenant}/assets?asset=${voiceId}`);
    await page.getByText('有权查看的直接使用位置', { exact: true }).click();
    await until(async()=>{
      if(await page.locator(`a[href*="cut=${cutId}"]`).count())return true;
      const more=page.getByRole('button',{name:'加载更多使用位置',exact:true});
      if(await more.isVisible()&&await more.isEnabled())await more.click();
      return false;
    },'current usage link absent after loading additional pages');
    await page.locator(`a[href*="cut=${cutId}"]`).click();
    await page.getByText('对白、声音与字幕', { exact: true }).waitFor();
    ok(page.url().includes(`cut=${cutId}`) && page.url().includes('tool=dialogue'), 'usage link lost exact cut context');
    await page.locator('video').first().waitFor();
    await until(async () => page.locator('video').first().evaluate(v => v.readyState >= 2), 'source did not decode after usage navigation');
    await page.screenshot({ path: 'output/playwright/editing-work/04-dialogue-bindings.png' });
    await page.setViewportSize({ width: 320, height: 740 });
    ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'dialogue panel overflows narrow viewport');
    await page.getByText('对白、声音与字幕', { exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'output/playwright/editing-work/05-dialogue-320.png' });
    await page.setViewportSize({ width: 1366, height: 900 });
    work = await read(workPath);
    ok(work.document.dramaBindings.every(b => b.shotRevisionId === shot.specRevisionId), 'saved fixed source silently upgraded');
    ok(errors.length === 0, errors.join('; '));
    return { productionBuild: true, sceneId: scene.id, cutId, shotId: shot.id, workRevision: work.revision, incompleteFormRecovered: true, fixedOldTextAndVoice: true, duplicateAudioDiagnosed: true, explicitMute: true, plannedSubtitleRequiresReview: true, manualAndAutomaticIssuesIndependent: true, exactSubtitleDuration: true, actualSourceDecoded: true, usageLink: true,usagePages, smallViewportOverflow: false, pageErrors: errors.length };
  } finally { page.off('pageerror', capture); }
}
